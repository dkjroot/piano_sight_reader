const assert=require('node:assert/strict');
module.exports=async function scorePracticeChecks(browser,url) {
  const context=await browser.newContext({viewport:{width:1440,height:900}}), page=await context.newPage(), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>{
    const input={id:'shared',name:'Shared test piano',state:'connected',connection:'closed',onmidimessage:null,async open(){this.connection='open';access.onstatechange?.();return this;},async close(){this.connection='closed';access.onstatechange?.();return this;}};
    const access={inputs:new Map([[input.id,input]]),onstatechange:null};
    window.sharedMidi={requests:0,send:data=>input.onmidimessage?.({data:Uint8Array.from(data)}),disconnect:()=>{input.state='disconnected';access.onstatechange?.();}};
    Object.defineProperty(navigator,'requestMIDIAccess',{value:async()=>{window.sharedMidi.requests++;return access;}});
  });
  try {
    await page.goto(url); await page.waitForSelector('.key');
    await page.evaluate(()=>{for(const [id,value] of Object.entries({hand:'both',size:10,span:'full',material:'sharps',low:0,high:127,'hand-span':24})) document.getElementById(id).value=value;document.getElementById('high').dispatchEvent(new Event('change'));});
    const original=await page.locator('#staff').innerHTML(), position=await page.locator('#phrase-position').innerText();
    const nodes=await page.evaluate(()=>{window.originalKeyboard=document.getElementById('keyboard');window.originalPanels=[document.getElementById('staff-panel'),document.getElementById('keyboard-panel')];return true;});
    await page.locator('#mode-study').click(); await page.waitForSelector('[data-score-note]');
    assert.equal(page.url(),url+'/','mode changes do not navigate');
    assert.equal(await page.locator('[data-score-note]').count(),17);
    assert.equal(await page.locator('.vf-stavetie').count(),1); assert.equal(await page.locator('.vf-tuplet').count(),1);
    assert.equal(await page.locator('#outline-settings').isVisible(),false); assert.equal(await page.locator('#study-settings').isVisible(),true);
    assert.equal(await page.locator('#density').isVisible(),true); assert.equal(await page.locator('#live-instrument').isVisible(),true);
    assert.equal(await page.evaluate(()=>window.sharedMidi.requests),0,'mode changes never request MIDI');
    assert.equal(await page.evaluate(()=>window.originalKeyboard===document.getElementById('keyboard') && window.originalPanels.every(node=>node.isConnected)),true);
    await page.locator('#connect').click(); await page.waitForFunction(()=>document.getElementById('midi-status').textContent.startsWith('Connected'));
    await page.evaluate(()=>{window.studySvg=document.querySelector('#authored-engraving svg');});
    const send=async data=>page.evaluate(data=>window.sharedMidi.send(data),data), on=async p=>send([0x90,p,100]), off=async p=>send([0x80,p,0]);
    await page.locator('#study-start').click(); await on(72);await on(64);await on(48);
    assert.equal(await page.locator('#keyboard [aria-pressed="true"]').count(),3); assert.equal(await page.locator('[data-practice=accepted]').count(),3);
    const svg=await page.locator('#authored-engraving').getAttribute('data-renders');
    await off(64); assert.match(await page.locator('#feedback').innerText(),/Hold again E4/);
    assert.equal(await page.evaluate(()=>window.studySvg===document.querySelector('#authored-engraving svg')),true,'MIDI feedback never re-engraves the score');
    await on(64); await page.waitForTimeout(20);
    await page.locator('#density').selectOption('custom');
    await page.locator('#staff-scale').fill('120'); await page.locator('#staff-scale').dispatchEvent('input');
    assert.equal(await page.locator('#staff-scale-value').innerText(),'120%'); assert.equal(await page.locator('#keyboard [aria-pressed="true"]').count(),3);
    await page.locator('#pause-practice').click(); assert.equal(await page.locator('#feedback').innerText(),'Paused');
    for(const bars of ['1','2','3','4','auto']) {
      await page.selectOption('#study-bars',bars);
      assert.equal(await page.locator('#feedback').innerText(),'Paused','bars per line preserves the practice gate');
      assert.equal(await page.locator('[data-score-note]').count(),17);
    }
    for(const p of [72,64,48]) await off(p);
    await page.locator('#mode-outline').click();
    assert.equal(await page.locator('#phrase-position').innerText(),position); assert.equal(await page.locator('#study-settings').isVisible(),false);
    await page.locator('#density').selectOption('auto');
    assert.equal(await page.locator('#staff').innerHTML(),original,'switching preserves pitch phrase');
    await page.selectOption('#source','cadence'); assert.equal(await page.locator('#cadence-shape').isVisible(),true); assert.equal(await page.locator('#advanced-kind').isVisible(),false);
    await page.selectOption('#source','random'); assert.equal(await page.locator('#cadence-shape').isVisible(),false);
    await page.locator('#mode-study').click(); await page.waitForSelector('[data-score-note]');
    assert.match(await page.locator('#feedback').innerText(),/Play|Paused/,'return preserves the study position with fresh articulation');
    await page.locator('#study-stop').click();
    assert.equal(await page.locator('#staff-panel #study-play').count(),1);
    assert.equal(await page.locator('#study-settings #study-play').count(),0);
    for(const id of ['key','hand','size','material','span','hand-span','left-density','right-density','left-leap','right-leap','ledger-limit']) {
      assert.equal(await page.locator('#'+id).isVisible(),true,'authored study exposes '+id);
      assert.equal(await page.locator('#'+id).isEnabled(),true);
    }
    await page.selectOption('#hand','left');
    await page.waitForFunction(()=>document.querySelectorAll('[data-score-note]').length>0 && document.querySelectorAll('[data-score-note]').length<17);
    assert.equal(await page.locator('#right-density').isVisible(),false);
    assert.equal(await page.locator('#left-density').isVisible(),true);
    await page.selectOption('#hand','both'); await page.waitForFunction(()=>document.querySelectorAll('[data-score-note]').length===17);
    await page.locator('#high').fill('0'); await page.locator('#high').dispatchEvent('change');
    await page.waitForFunction(()=>document.getElementById('feedback').textContent.includes('No retained notes'));
    assert.equal(await page.locator('[data-score-note]').count(),0,'an empty filter never leaves a stale score visible');
    assert.equal(await page.locator('#study-start').isDisabled(),true);
    await page.locator('#high').fill('127'); await page.locator('#high').dispatchEvent('change');
    await page.waitForFunction(()=>document.querySelectorAll('[data-score-note]').length===17);
    await page.selectOption('#right-density','1');
    await page.waitForFunction(()=>document.querySelectorAll('[data-score-note]').length<17);
    await page.selectOption('#right-density','5'); await page.waitForFunction(()=>document.querySelectorAll('[data-score-note]').length===17);
    await page.selectOption('#study-source','notation-cases'); await page.waitForSelector('[data-score-page="2"]');
    await page.selectOption('#study-bars','3');
    assert.equal(await page.locator('.score-page').nth(1).getAttribute('id'),'authored-engraving-page-6','page boundaries preserve complete three-bar rows');
    assert.equal(await page.locator('.score-page svg').nth(1).getAttribute('data-score-page'),'2');
    await page.selectOption('#study-bars','auto');
    assert.ok(await page.locator('.vf-tuplet').count()>=4); assert.equal(await page.locator('.vf-stavetie').count(),2);
    await page.selectOption('#study-source','tempo-curves');
    await page.waitForFunction(()=>document.getElementById('practice-title').textContent==='Study in gradual tempo');
    assert.equal(await page.locator('[data-tempo-bpm]').count(),4);
    assert.equal(await page.locator('[data-tempo-curve="linear"]').count(),2);
    assert.match(await page.locator('[data-tempo-bpm="120"]').textContent(),/rit\./);
    assert.match(await page.locator('[data-tempo-bpm="60"]').first().textContent(),/accel\./);
    await page.selectOption('#study-tempo','steady');
    assert.equal(await page.evaluate(()=>localStorage.getItem('piano-sight-reader-study-tempo')),'steady');
    const restored=await context.newPage();
    await restored.goto(url+'/?view=study&study=tempo-curves');
    await restored.waitForSelector('[data-tempo-bpm]');
    assert.equal(await restored.locator('#study-tempo').inputValue(),'steady');
    assert.equal(await restored.locator('[data-tempo-curve="linear"]').count(),2,'teaching tempo preserves written changes');
    await restored.close();
    await page.selectOption('#study-tempo','score');
    await page.bringToFront(); await page.locator('#staff-panel').screenshot({path:'test-results/tempo-curves-study.png'});
    await page.selectOption('#study-source','meter-groups');
    await page.waitForFunction(()=>document.getElementById('practice-title').textContent==='Study in meter and beat groups');
    assert.equal(await page.locator('#authored-engraving svg').first().getAttribute('data-meter-groups'),'3+3|3+3|2+3|3+2|1+1+1|1+1+1');
    assert.equal(await page.locator('.vf-beam').count(),11,'compound 3+3, asymmetric groups and simple beats control beaming');
    const aligned=await page.evaluate(()=>['compound-melody-3-note','compound-bass-1-note'].map(id=>{const b=document.querySelector(`[data-score-note="${id}"] text`).getBoundingClientRect();return b.x+b.width/2;}));
    assert.ok(Math.abs(aligned[0]-aligned[1])<2,'independent voices align by musical time');
    await page.evaluate(()=>window.scrollTo(0,0)); await page.screenshot({path:'test-results/meter-groups-study.png'});

    await page.locator('#mode-outline').click();
    await page.locator('#score-file').setInputFiles('tests/fixtures/polyphony.mid');
    await page.waitForFunction(()=>!document.getElementById('practice-score').disabled);
    await page.evaluate(()=>{for(const [id,value] of Object.entries({hand:'both',span:'full',low:21,high:108,size:10})) document.getElementById(id).value=value;document.getElementById('high').dispatchEvent(new Event('change'));});
    await page.locator('#practice-score').click();
    for(const id of ['hand-span','right-density','left-density','right-leap','left-leap','ledger-limit']) assert.equal(await page.locator('#'+id).isVisible(),true,'MIDI pitch practice exposes '+id);
    await page.locator('#mode-study').click(); await page.waitForSelector('[data-score-note]');
    await page.waitForFunction(()=>document.getElementById('exercise-summary').textContent.includes('Loaded MIDI'));
    assert.match(await page.locator('#practice-title').innerText(),/polyphony/); assert.ok(await page.locator('.vf-stave').count()>0);
    assert.equal(await page.locator('#key').isVisible(),true); assert.equal(await page.locator('#play-source').isVisible(),true,'source playback is available in study mode');
    await page.locator('#study-start').click(); assert.match(await page.locator('#feedback').innerText(),/Play/);
    await page.locator('#study-stop').click(); await page.locator('#study-play').click();
    await page.waitForFunction(()=>document.getElementById('feedback').textContent==='Playing study');
    await page.locator('#study-audio-pause').click(); assert.equal(await page.locator('#feedback').innerText(),'Playback paused');
    await page.locator('#mode-outline').click(); assert.equal(await page.locator('#practice-title').innerText(),'Local MIDI outline');
    await page.locator('#mode-study').click(); await page.waitForSelector('[data-score-note]');
    let releaseManifest;
    const waiting=new Promise(resolve=>page.route('**/static/audio/salamander/manifest.json',route=>{releaseManifest=()=>route.continue();resolve();}));
    await page.evaluate(()=>{window.studySampleStarts=0;const create=AudioContext.prototype.createBufferSource;AudioContext.prototype.createBufferSource=function(...args){const source=create.apply(this,args),start=source.start;source.start=(...values)=>{window.studySampleStarts++;return start.apply(source,values);};return source;};});
    await page.selectOption('#reference-instrument','acoustic'); await waiting;
    await page.locator('#study-play').click(); await page.locator('#study-stop').click(); await releaseManifest();
    await page.waitForFunction(()=>document.getElementById('sound-status').textContent!=='Loading acoustic piano…');
    assert.equal(await page.evaluate(()=>window.studySampleStarts),0,'cancelled sample loading must never restart study audio');
    await page.unroute('**/static/audio/salamander/manifest.json');
    await page.selectOption('#reference-instrument','piano');
    await page.locator('#mode-outline').click(); await page.selectOption('#source','cadence');
    await page.locator('#mode-study').click(); await page.waitForSelector('[data-score-note]');
    assert.equal(await page.locator('#material').isEnabled(),true,'a loaded MIDI study must not inherit disabled harmonic-generator filters');
    await page.selectOption('#material','flats');
    await page.waitForFunction(()=>!document.getElementById('study-start').disabled);
    await page.locator('#mode-outline').click();
    assert.equal(await page.locator('#material').isVisible(),false,'generated harmonic branch restores its applicable controls');
    assert.equal(await page.inputValue('#material'),'flats','hiding an inapplicable control preserves its value');
    await page.locator('#mode-study').click(); await page.waitForSelector('[data-score-note]');
    for(const theme of ['light','dark']) {
      if(await page.locator('html').getAttribute('data-theme')!==theme) await page.locator('#theme-toggle').click();
      await page.screenshot({path:`test-results/shared-study-${theme}.png`,fullPage:false});
    }
    await page.setViewportSize({width:360,height:800}); await page.waitForTimeout(150);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.setViewportSize({width:1440,height:900});
    await page.selectOption('#library-piece','rachmaninoff-op3-2'); await page.locator('#load-piece').click();
    await page.waitForFunction(()=>document.getElementById('score-status').textContent.includes('Prelude in C-sharp minor'));
    await page.selectOption('#suggested-passages','1');
    await page.waitForFunction(()=>document.getElementById('practice-title').textContent.includes('Prelude in C-sharp minor'));
    await page.waitForFunction(()=>!document.getElementById('study-start').disabled);
    await page.selectOption('#study-bars','1');
    assert.ok(await page.locator('[data-score-note]').evaluateAll(notes=>new Set(notes.map(note=>note.getAttribute('aria-label').split(' · ')[1])).size)<=4,'Rachmaninoff Section 2 uses chord voices');
    assert.equal(await page.locator('.vf-stavenote').evaluateAll(nodes=>nodes.some(node=>node.querySelectorAll('[data-score-note]').length>1)),true);
    const tieSides=await page.locator('.vf-stavetie').evaluateAll(ties=>ties.map(tie=>[tie.dataset.scoreVoice,tie.dataset.tieSide]));
    assert.ok(tieSides.length>0);
    for(const voice of new Set(tieSides.map(tie=>tie[0]))) assert.equal(new Set(tieSides.filter(tie=>tie[0]===voice).map(tie=>tie[1])).size,1,'ties stay on a consistent side within each voice');
    const header=await page.evaluate(()=>{
      const rect=id=>document.getElementById(id).getBoundingClientRect(), middle=b=>b.y+b.height/2;
      return {title:middle(rect('practice-title')),bar:middle(rect('phrase-position')),bars:middle(rect('study-bars-control')),scale:middle(document.querySelector('.staff-scale').getBoundingClientRect()),titleGap:rect('phrase-position').left-rect('practice-title').right,groupGap:document.querySelector('.staff-scale').getBoundingClientRect().left-rect('study-bars-control').right};
    });
    assert.ok(Math.max(header.title,header.bar,header.bars,header.scale)-Math.min(header.title,header.bar,header.bars,header.scale)<2,JSON.stringify(header));
    assert.ok(header.titleGap>=16 && header.groupGap>=20,JSON.stringify(header));
    await page.evaluate(()=>window.scrollTo(0,0)); await page.screenshot({path:'test-results/rach-section-two.png'});
    await page.locator('#density').selectOption('custom');
    await page.locator('#staff-scale').fill('160'); await page.locator('#staff-scale').dispatchEvent('input');
    for(const height of [180,300,600]) {
      await page.locator('[aria-label="Resize staff"]').focus();
      for(let step=0;step<height/40;step++) await page.keyboard.press('Shift+ArrowDown'); await page.waitForTimeout(150);
      const fit=await page.locator('#staff').evaluate(pane=>({width:pane.clientWidth,scroll:pane.scrollWidth,svg:[...pane.querySelectorAll('svg')].map(svg=>svg.getBoundingClientRect().width)}));
      assert.ok(fit.scroll<=fit.width+1,JSON.stringify(fit));
      assert.ok(fit.svg.every(width=>width<=fit.width+1),'engraving fits the space beside the vertical scrollbar');
    }
    assert.equal(await page.locator('.score-page').first().getAttribute('data-bars-per-line'),'1');
    await page.locator('#study-position').fill('2'); await page.locator('#study-position').dispatchEvent('input');
    await page.selectOption('#study-bars','2'); assert.equal(await page.inputValue('#study-position'),'2','reflow preserves the study position');
    assert.equal(await page.locator('.score-page').first().getAttribute('data-bars-per-line'),'2');
    await page.reload(); assert.equal(await page.inputValue('#study-bars'),'2','bars per line is remembered');
    assert.deepEqual(errors,[]);
    await page.goto(url+'/notation-study?study=notation-cases'); await page.waitForSelector('[data-score-page="2"]');
    assert.match(page.url(),/view=study/);
  } finally {await context.close();}
};
