const assert=require('node:assert/strict');
module.exports=async function uiFlowChecks(browser,url) {
  const context=await browser.newContext({viewport:{width:3840,height:2160}}), page=await context.newPage(), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>{
    const input={id:'flow',name:'Flow test piano',state:'connected',connection:'closed',async open(){this.connection='open';return this;},async close(){return this;}};
    window.flowMidi=data=>input.onmidimessage?.({data:Uint8Array.from(data)});
    Object.defineProperty(navigator,'requestMIDIAccess',{value:async()=>({inputs:new Map([['flow',input]])})});
  });
  const bounds=selector=>page.locator(selector).evaluate(node=>{const b=node.getBoundingClientRect();return {left:b.left,width:b.width};});
  const on=pitch=>page.evaluate(pitch=>window.flowMidi([0x90,pitch,100]),pitch);
  const off=pitch=>page.evaluate(pitch=>window.flowMidi([0x80,pitch,0]),pitch);
  try {
    await page.goto(url); await page.waitForSelector('.note');
    const main=await bounds('main'), settings=await bounds('.settings-grid'), header=await bounds('header');
    await page.locator('#staff-panel .layout-resize').focus();
    for(let i=0;i<20;i++) await page.keyboard.press('Shift+ArrowRight');
    const after=await bounds('main');
    assert.equal(after.width,main.width); assert.ok(after.width<=1120);
    assert.ok(Math.abs(after.left-main.left)<1);
    assert.deepEqual(await bounds('.settings-grid'),settings,'resizing a panel must not widen the settings');
    assert.deepEqual(await bounds('header'),header,'header remains centered');
    assert.ok((await bounds('#staff-panel')).width>main.width,'the playing panel can expand beyond the centered settings');
    await page.locator('#keyboard-panel .layout-resize').focus(); await page.keyboard.press('Shift+ArrowRight');
    assert.deepEqual(await bounds('.settings-grid'),settings,'keyboard resizing also leaves the settings alone');
    await page.setViewportSize({width:1440,height:900}); await page.selectOption('#density','auto');
    await page.evaluate(()=>{for(const [id,value] of Object.entries({hand:'right',size:1,span:'full',material:'sharps',low:21,high:108})) document.getElementById(id).value=value;document.getElementById('high').dispatchEvent(new Event('change'));});
    await page.locator('#score-file').setInputFiles('tests/fixtures/polyphony.mid');
    await page.waitForFunction(()=>!document.getElementById('practice-score').disabled);
    await page.locator('#practice-score').click();
    await page.locator('#passage-end').fill('1'); await page.locator('#passage-end').dispatchEvent('change');
    assert.equal(await page.locator('#source').isVisible(),true);
    for(const id of ['end-repeat','end-new','end-stop']) assert.equal(await page.locator('#'+id).isEnabled(),true);
    assert.equal(await page.evaluate(()=>document.getElementById('source').getBoundingClientRect().top<document.getElementById('key').getBoundingClientRect().top),true);
    await page.locator('#end-new').check();
    await page.locator('#connect').click(); await page.waitForFunction(()=>document.getElementById('midi-status').textContent.startsWith('Connected'));
    await on(64);
    await page.waitForFunction(()=>document.getElementById('score-playing').textContent.includes('source attacks 2–2'));
    await on(67);
    await page.waitForFunction(()=>document.getElementById('feedback').textContent==='✓ Passage complete');
    await off(64); await off(67);
    assert.equal(await page.locator('#restart-pitch').isVisible(),true);
    await page.locator('#end-repeat').check();
    const count=+(await page.locator('#count').innerText());
    await on(67); assert.equal(+(await page.locator('#count').innerText()),count+1);
    assert.notEqual(await page.locator('#feedback').innerText(),'✓ Passage complete');
    await off(67); await on(67); assert.equal(+(await page.locator('#count').innerText()),count+2); await off(67);
    await page.locator('#end-stop').check(); await on(67);
    assert.equal(await page.locator('#feedback').innerText(),'✓ Passage complete'); await off(67);
    await page.locator('#restart-pitch').click(); assert.notEqual(await page.locator('#feedback').innerText(),'✓ Passage complete');
    await page.selectOption('#source','random');
    assert.equal(await page.inputValue('#source'),'random'); assert.equal(await page.locator('#practice-title').innerText(),'Random pitches');
    assert.equal(await page.locator('#return-random').count(),0);
    const randomPhrase=await page.locator('#staff').innerHTML();
    await page.locator('#mode-study').click(); await page.waitForSelector('[data-score-note]');
    await page.selectOption('#study-source','independent-voices'); await page.waitForFunction(()=>document.getElementById('practice-title').textContent==='Study in independent voices');
    assert.equal(await page.locator('#study-loop').isChecked(),true,'study passages loop by default');
    await page.locator('#study-loop').uncheck(); await page.selectOption('#study-speed','2');
    await page.selectOption('#study-exit','1');
    await page.locator('#study-play').click(); await page.waitForFunction(()=>document.getElementById('feedback').textContent==='Playback complete');
    await page.locator('#study-play').click(); await page.waitForFunction(()=>document.getElementById('feedback').textContent==='Playing study');
    await page.waitForFunction(()=>document.getElementById('feedback').textContent==='Playback complete');
    await page.locator('#study-loop').check(); await page.locator('#study-play').click();
    await page.waitForTimeout(650); assert.equal(await page.locator('#feedback').innerText(),'Playing study','audio repeats the selected cut while Loop is enabled');
    await page.locator('#study-loop').uncheck();
    const last=await page.locator('#study-exit option').last().getAttribute('value'); await page.selectOption('#study-exit',last); await page.selectOption('#study-entry','1');
    await page.locator('#study-position').fill('2'); await page.locator('#study-position').dispatchEvent('input');
    await page.locator('#study-play').click(); await page.waitForFunction(()=>document.getElementById('feedback').textContent==='Playing study');
    await page.locator('#study-audio-pause').click(); const paused=await page.inputValue('#study-position');
    assert.notEqual(paused,'0'); assert.equal(await page.locator('#study-play').innerText(),'Resume study');
    await page.locator('#study-stop').click(); assert.equal(await page.inputValue('#study-position'),'1');
    assert.equal(await page.locator('#study-play').innerText(),'Play study');
    await page.locator('#study-play').click(); await page.waitForFunction(()=>document.getElementById('feedback').textContent==='Playing study');
    await page.locator('#study-rewind').click(); await page.waitForFunction(()=>document.getElementById('feedback').textContent==='Playing study');
    assert.equal(await page.inputValue('#study-position'),'1');
    await page.locator('#study-stop').click(); await page.locator('#mode-outline').click();
    assert.equal(await page.locator('html').getAttribute('data-workspace'),'outline'); assert.equal(await page.inputValue('#source'),'random');
    assert.equal(await page.locator('#staff').innerHTML(),randomPhrase,'returning to the existing random source preserves the phrase');
    assert.deepEqual(errors,[]);
  } finally {await context.close();}
};
